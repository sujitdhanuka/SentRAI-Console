const ENV_TO_FLAG = Object.fromEntries(Object.entries(EPIC_FLAGS).map(([k, env]) => [env, k])) as Record<string, keyof FeatureFlags>;

export interface ImplementationSummary {
  implemented: number;
  partial: number;
  gap: number;
  notApplicable: number;
  /** Requirements a product could implement (all but N/A). */
  applicable: number;
  total: number;
  unit: string;
  /** Rows counted at their earlier status because a flag they need is off here. */
  heldBackByFlags: number;
}

/** Implementation status for a framework with this deployment's flags; null when no assessment exists. */
export function implementationSummary(frameworkId: string, flags: FeatureFlags): ImplementationSummary | null {
  const fw = IMPLEMENTATION_STATUS[frameworkId];
  if (!fw) return null;
  const s = { I: 0, P: 0, G: 0, N: 0 };
  let held = 0;
  for (const [, before, after, needs] of fw.rows) {
    const on = flags.governanceV2 && needs.every((env) => ENV_TO_FLAG[env] !== undefined && flags[ENV_TO_FLAG[env]]);
    const status = on ? after : before;
    if (!on && after !== before) held++;
    s[status]++;
  }
  return {
    implemented: s.I,
    partial: s.P,
    gap: s.G,
    notApplicable: s.N,
    applicable: fw.rows.length - s.N,
    total: fw.rows.length,
    unit: fw.unit,
    heldBackByFlags: held,
  };
}
